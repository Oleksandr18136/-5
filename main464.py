# Зчитуємо текст
text = input("Введіть текст (слова через пробіл): ").split()

# Зчитуємо порядковий номер слова (нумерація з 1)
index = int(input("Введіть номер слова: "))

# Отримуємо потрібне слово та його першу літеру
word = text[index - 1]
print(f"Перша літера {index}-го слова: {word[0]}")